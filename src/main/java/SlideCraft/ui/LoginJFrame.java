package SlideCraft.ui;

public class LoginJFrame extends javax.swing.JFrame {
    public LoginJFrame() {
        this.setSize(488, 430);
        this.setVisible(true);
        //设置界面的标题
        this.setTitle("登入");
        //设置界面置顶
        this.setAlwaysOnTop(true);
        this.setLocationRelativeTo(null);
        //设置关闭模式
        this.setDefaultCloseOperation(3);
        //让显示显示出来
        this.setVisible(true);
    }
}
